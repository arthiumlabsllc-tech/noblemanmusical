/** Get a product by slug */
export function getProduct(slug: string): SeedProduct | undefined {
  return products.find((p) => p.slug === slug);
}

/** Get products by category */
export function getProductsByCategory(categorySlug: string): SeedProduct[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

/** Get featured products */
export function getFeaturedProducts(): SeedProduct[] {
  return products.filter((p) => p.isFeatured);
}

/** Search products */
export function searchProducts(query: string): SeedProduct[] {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.tags.some((t) => t.includes(q)) ||
      p.categoryName.toLowerCase().includes(q)
  );
}

/** Get all brands */
export function getBrands(): string[] {
  return [...new Set(products.map((p) => p.brand))].sort();
}

/** Get price range */
export function getPriceRange(): { min: number; max: number } {
  const prices = products.map((p) => p.price);
  return { min: Math.min(...prices), max: Math.max(...prices) };
}
